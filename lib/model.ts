// Token Radar's model, radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks every protocol the snapshot records as pre-token (no market
// cap, no CoinGecko id, no symbol) that is not a wrapped, staked or bridged
// product of a token that already trades. The watchlist is the floor: all 40
// of its slugs are ranked, and the early radar adds every other rankable
// pre-token protocol below the floor, so the board answers "which pre-token
// protocol is worth farming next" over the whole universe, not just the top 40.
//
// Implied value follows only from the snapshot's own figures. The one number
// the starter's flat multiple cannot give is what a token in this protocol's
// own line of business is worth: so the multiple is read off the snapshot
// itself, per category, from the protocols whose tokens already trade:
//
//   multiple[category] = median(mcap_usd / tvl_usd) over live-token
//                        protocols in that category with tvl > 0 and
//                        mcap > 0, when at least 3 of them exist;
//                        otherwise the global median over all such
//                        protocols. Clamped to [0.05, 1.50].
//
//   base        = tvl_usd x multiple[category]
//   growth      = clamp(change_7d, -60, 120) per cent
//   growthMult  = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity    = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age unknown: 365)
//   implied     = max(1, round(base x growthMult x maturity))
//
// No protocol name is ever special-cased: the same function scores every
// row, and the multiples are recomputed from whatever snapshot is fed in, so
// the radar stays dynamic on a future snapshot. Research notes (token checks,
// points programs, funding) are annotations on a row only: they never change
// a rank or an implied value.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

