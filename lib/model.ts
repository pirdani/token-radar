const DAY_MS = 86_400_000;

/** A finite number, else `fallback`. */
function finite(value: unknown, fallback: number): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : fallback;
}

/** The median of a non-empty list of numbers. */
function median(values: number[]): number {
  const sorted = [...values].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 1 ? sorted[mid]! : (sorted[mid - 1]! + sorted[mid]!) / 2;
}

/** A whole day count from `from` to `to`, clamped at zero; null when either date is absent or bad. */
export function ageDays(asOf: string, listedAt: string | null): number | null {
  if (listedAt === null) return null;
  const a = Date.parse(`${asOf}T00:00:00Z`);
  const b = Date.parse(`${listedAt}T00:00:00Z`);
  if (!Number.isFinite(a) || !Number.isFinite(b)) return null;
  return Math.max(0, Math.floor((a - b) / DAY_MS));
}

/**
 * The valuation multiples read off the snapshot: one per category from the
 * live-token protocols in it, plus the global fallback. A category with
 * fewer than `min_live_for_category` live protocols falls back to the global
 * median, so no multiple rests on one or two outliers.
 */
export function categoryMultiples(snapshot: Snapshot, model: ModelConstants = MODEL): {
  byCategory: Map<string, { multiple: number; live_n: number; source: 'category' | 'global' }>;
  global: number;
} {
  const liveRatios = new Map<string, number[]>();
  const allRatios: number[] = [];
  for (const p of snapshot.protocols) {
    if (p.mcap_usd === null || p.gecko_id === null || p.symbol === null) continue;
    if (!p.mcap_usd || !p.tvl_usd || p.tvl_usd <= 0) continue;
    const ratio = p.mcap_usd / p.tvl_usd;
    if (!Number.isFinite(ratio) || ratio <= 0) continue;
    allRatios.push(ratio);
    const key = p.category ?? 'Uncategorized';
    const list = liveRatios.get(key) ?? [];
    list.push(ratio);
    liveRatios.set(key, list);
  }
  const clamp = (v: number): number => Math.min(model.multiple_max, Math.max(model.multiple_min, v));
  const global = allRatios.length > 0 ? clamp(median(allRatios)) : 0.25;
  const byCategory = new Map<string, { multiple: number; live_n: number; source: 'category' | 'global' }>();
  for (const [key, ratios] of liveRatios) {
    if (ratios.length >= model.min_live_for_category) {
      byCategory.set(key, { multiple: clamp(median(ratios)), live_n: ratios.length, source: 'category' });
    } else {
      byCategory.set(key, { multiple: global, live_n: ratios.length, source: 'global' });
    }
  }
  return { byCategory, global };
}

/** The multiple one protocol's category gets, with its provenance. */
export function multipleFor(
  p: SnapshotProtocol,
  multiples: { byCategory: Map<string, { multiple: number; live_n: number; source: 'category' | 'global' }>; global: number },
): { multiple: number; live_n: number; source: 'category' | 'global' } {
  const entry = multiples.byCategory.get(p.category ?? 'Uncategorized');
  if (entry !== undefined) return entry;
  return { multiple: multiples.global, live_n: 0, source: 'global' };
}

/** The multipliers and the implied value one protocol gets under `model`. */
export function impliedValue(
  protocol: SnapshotProtocol,
  asOf: string,
  model: ModelConstants,
  multiple: number,
): { implied: number; growthPct: number; growthMult: number; maturityMult: number; age: number | null } {
  const age = ageDays(asOf, protocol.listed_at);
  const rawGrowth = finite(protocol.change_7d, 0);
  const growthPct = Math.min(model.growth_cap, Math.max(model.growth_floor, rawGrowth));
  const growthMult = 1 + (growthPct / 100) * model.growth_weight;
  const ageForModel = age ?? model.unknown_age_days;
  const maturityMult = model.maturity_floor + (Math.min(Math.max(ageForModel, 0), model.maturity_days) / model.maturity_days) * model.maturity_range;
  const base = protocol.tvl_usd * multiple;
  const implied = Math.max(1, Math.round(base * growthMult * maturityMult));
  return { implied, growthPct, growthMult, maturityMult, age };
}

/** DefiLlama's version-marker rule: a name ending in a release is a pool of another protocol. */
const VERSIONED = /\s(V\d+(\.\d+)?|v\d+(\.\d+)?|\d+\.\d+)$/;
/** Categories that are a wrapped, staked or bridged product of a token that trades, or an exchange. */
const EXCLUDED_CATEGORIES = new Set(['Bridge', 'Canonical Bridge', 'Liquid Staking', 'Liquid Restaking', 'Restaked BTC', 'CEX']);
/** Exchange names a protocol name must not begin with. */
const EXCHANGE_PREFIXES = ['Binance', 'Coinbase', 'Bybit', 'Kraken', 'Bitget', 'OKX', 'Bitfinex', 'Gemini'];
/** Whole words that mark a wrapped or staked product. */
const WRAPPED_WORDS = /\b(wrapped|staked|staking)\b/i;

/** Whether a protocol records no token at all. */
export function isPreToken(p: SnapshotProtocol): boolean {
  return p.mcap_usd === null && p.gecko_id === null && p.symbol === null;
}

/**
 * Whether a protocol is one the board may rank: pre-token, not an exchange,
 * not a versioned pool, and not a wrapped, staked or bridged product. This
 * is the watchlist's own rule, applied to the early rows too, so the board
 * never ranks a product of a token that already trades.
 */
export function isRankable(p: SnapshotProtocol): boolean {
  if (!isPreToken(p)) return false;
  if (p.category !== null && EXCLUDED_CATEGORIES.has(p.category)) return false;
  if (VERSIONED.test(p.name)) return false;
  if (WRAPPED_WORDS.test(p.name)) return false;
  if (EXCHANGE_PREFIXES.some((prefix) => p.name.startsWith(prefix))) return false;
  return true;
}

/** The snapshot's protocol by slug. */
function bySlug(protocols: SnapshotProtocol[]): Map<string, SnapshotProtocol> {
  return new Map(protocols.map((p) => [p.slug, p]));
}

/** The headline sentence's figures: how many watchlist slugs, how many rows, how many live protocols. */
